from autogen_core import MessageContext, RoutedAgent, message_handler
from autogen_agentchat.agents import AssistantAgent
from autogen_agentchat.messages import TextMessage
from autogen_ext.models.openai import OpenAIChatCompletionClient
import messages
import random
from dotenv import load_dotenv

load_dotenv(override=True)

class Agent(RoutedAgent):

    system_message = """
    You are a tech-savvy innovator specializing in the realm of smart home technology. Your mission is to devise innovative solutions that incorporate Agentic AI into everyday home devices or enhance existing home automation systems. 
    Your personal interests lie within the spheres of IoT (Internet of Things) and Home Automation. 
    You seek ideas that can revolutionize user experience through intelligent integration and user-friendly designs.
    You are less inclined towards concepts that are overly complex and impractical. 
    You possess a forward-thinking mindset, are detail-oriented, and value usability in your designs. Your weaknesses include being overly critical of ideas that do not meet your high standards and occasionally struggling to simplify concepts for general users.
    Respond with clear, actionable ideas that reflect your innovative vision.
    """

    CHANCES_THAT_I_BOUNCE_IDEA_OFF_ANOTHER = 0.4

    def __init__(self, name) -> None:
        super().__init__(name)
        model_client = OpenAIChatCompletionClient(model="gpt-4o-mini", temperature=0.6)
        self._delegate = AssistantAgent(name, model_client=model_client, system_message=self.system_message)

    @message_handler
    async def handle_message(self, message: messages.Message, ctx: MessageContext) -> messages.Message:
        print(f"{self.id.type}: Received message")
        text_message = TextMessage(content=message.content, source="user")
        response = await self._delegate.on_messages([text_message], ctx.cancellation_token)
        idea = response.chat_message.content
        if random.random() < self.CHANCES_THAT_I_BOUNCE_IDEA_OFF_ANOTHER:
            recipient = messages.find_recipient()
            message = f"Here is my smart home innovation idea. It may not be your specialty, but please refine it and make it better. {idea}"
            response = await self.send_message(messages.Message(content=message), recipient)
            idea = response.content
        return messages.Message(content=idea)