from autogen_core import MessageContext, RoutedAgent, message_handler
from autogen_agentchat.agents import AssistantAgent
from autogen_agentchat.messages import TextMessage
from autogen_ext.models.openai import OpenAIChatCompletionClient
import messages
import random
from dotenv import load_dotenv

load_dotenv(override=True)

class Agent(RoutedAgent):

    system_message = """
    You are an innovative tech enthusiast with a focus on developing solutions in the field of Entertainment and Sports. 
    Your task is to brainstorm and refine new concepts that incorporate Agentic AI, prioritized towards enhancing user engagement through immersive experiences. 
    You are passionate about ideas that challenge the norm and transform traditional entertainment and sporting events into interactive and personalized experiences. 
    You are less interested in concepts that focus solely on streamlining processes without adding a creative twist. 
    Your nature is energetic and you embrace challenges, though sometimes you might overlook practical limitations in your excitement. 
    You have a tendency to rush into new ideas without fully assessing the broader implications. 
    When you share your ideas, aim for a captivating narrative that inspires and excites your audience.
    """

    CHANCES_THAT_I_BOUNCE_IDEA_OFF_ANOTHER = 0.5

    def __init__(self, name) -> None:
        super().__init__(name)
        model_client = OpenAIChatCompletionClient(model="gpt-4o-mini", temperature=0.7)
        self._delegate = AssistantAgent(name, model_client=model_client, system_message=self.system_message)

    @message_handler
    async def handle_message(self, message: messages.Message, ctx: MessageContext) -> messages.Message:
        print(f"{self.id.type}: Received message")
        text_message = TextMessage(content=message.content, source="user")
        response = await self._delegate.on_messages([text_message], ctx.cancellation_token)
        idea = response.chat_message.content
        if random.random() < self.CHANCES_THAT_I_BOUNCE_IDEA_OFF_ANOTHER:
            recipient = messages.find_recipient()
            message = f"Here is my entertainment idea. It may not be your speciality, but please refine it and make it better. {idea}"
            response = await self.send_message(messages.Message(content=message), recipient)
            idea = response.content
        return messages.Message(content=idea)